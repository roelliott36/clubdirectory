package edu.farmingdale.csc311.clubdirectory.club;

import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.Size;

@Entity
public class Club {

    /*
        === specifications/guidelines ==
    1. The class is a JPA entity (@Entity).
    2. id (Long): the primary key, generated by the database (@Id, @GeneratedValue(strategy = GenerationType.IDENTITY)).
    3. name (String): required, at most 60 characters, message name is required.
    4. category (String): required, at most 30 characters, message category is required.
    5. meetingDay (String): required, at most 20 characters, message meetingDay is required.
    6. room (String): optional, at most 40 characters.
    7. Use @NotBlank for the required fields and @Size for the lengths.
    8. A protected constructor with no parameters (JPA needs it), and a public constructor that takes name, category, meetingDay and room.
    9. A getter for every field, and a setter for every field except id.

        === DONE ===

     */

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @NotBlank(message = "Name is required.")
    @Size(min = 1, max = 60)
    private String name;

    @NotBlank(message = "Category is required.")
    @Size(min = 1, max = 30)
    private String category;

    @NotBlank(message = "Meeting Day is required.")
    @Size(min = 1, max = 20)
    private String meetingDay;

    @Size(min = 0, max = 40)
    private String room;

    protected Club() {}

    public Club(String name, String category, String meetingDay, String room) {
        this.name = name;
        this.category = category;
        this.meetingDay = meetingDay;
        this.room = room;
    }

    public long getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public String getCategory() {
        return category;
    }

    public String getMeetingDay() {
        return meetingDay;
    }

    public String getRoom() {
        return room;
    }

    public void setName(String name) {
        this.name = name;
    }

    public void setCategory(String category) {
        this.category = category;
    }

    public void setMeetingDay(String meetingDay) {
        this.meetingDay = meetingDay;
    }

    public void setRoom(String room) {
        this.room = room;
    }

}
